/// Standing/walking alpha contours (threshold 96, simplified within 2 source
/// pixels) in crop coordinates; original sprite sheets remain unchanged.
/// Placement matches ChildCharacter's common pose scale and bottom alignment.
Path childCharacterOutlinePath(
  ChildPoseName pose,
  ChildGender gender,
  Size size,
) {
  assert(pose == ChildPoseName.stand || pose == ChildPoseName.walk);
  final source = ChildCharacter.sourceRectFor(pose, gender);
  final standing = ChildCharacter.sourceRectFor(ChildPoseName.stand, gender);
  final height = math.min(size.height, size.width / .55);
  final scale = height / standing.height;
  final width = source.width * scale;
  final poseHeight = source.height * scale;
  final left = (size.width - width) / 2;
  final top = size.height - poseHeight;
  final points = switch ((gender, pose)) {
    (ChildGender.boy, ChildPoseName.walk) => _boyWalk,
    (ChildGender.boy, _) => _boyStand,
    (_, ChildPoseName.walk) => _girlWalk,
    _ => _girlStand,
  };
  final path = Path();
  for (var index = 0; index < points.length; index++) {
    final x = left + points[index].dx * width;
    final y = top + points[index].dy * poseHeight;
    final mirroredX = pose == ChildPoseName.walk ? size.width - x : x;
    if (index == 0) {
      path.moveTo(mirroredX, y);
    } else {
      path.lineTo(mirroredX, y);
    }
  }
  return path..close();
}

